/// All entries, in alpha-2 order.
pub fn all() -> &'static [Country] {
    COUNTRIES
}

/// Number of entries in the table.
pub fn count() -> usize {
    COUNTRIES.len()
}

/// Looks a country up by its two-letter code (upper case).
pub fn by_alpha2(code: &str) -> Option<&'static Country> {
    COUNTRIES
        .binary_search_by(|c| c.alpha2.cmp(code))
        .ok()
        .map(|i| &COUNTRIES[i])
}

/// Looks a country up by its three-letter code (upper case).
pub fn by_alpha3(code: &str) -> Option<&'static Country> {
    // The table is sorted by alpha-2, not alpha-3, so this is a scan.
    COUNTRIES.iter().find(|c| c.alpha3 == code)
}

/// Looks a country up by its numeric code.
pub fn by_numeric(code: u16) -> Option<&'static Country> {
    COUNTRIES.iter().find(|c| c.numeric == code)
}

/// Looks a country up by its English short name, ignoring case.
pub fn by_name(name: &str) -> Option<&'static Country> {
    COUNTRIES.iter().find(|c| c.name.eq_ignore_ascii_case(name))
}

/// The ISO 4217 currency code for a two-letter country code, if the
/// territory has one.
pub fn currency(alpha2: &str) -> Option<&'static str> {
    by_alpha2(alpha2)
        .map(|c| c.currency)
        .filter(|cur| !cur.is_empty())
}

/// The dialling prefix for a two-letter country code, if the territory
/// has one.
pub fn dial_code(alpha2: &str) -> Option<&'static str> {
    by_alpha2(alpha2)
        .map(|c| c.dial)
        .filter(|d| !d.is_empty())
}

/// Every country that uses `currency` (an ISO 4217 code), in alpha-2 order.
pub fn using_currency(currency: &str) -> Vec<&'static Country> {
    COUNTRIES
        .iter()
        .filter(|c| c.currency == currency)
        .collect()
}

/// Every country whose dialling prefix starts with `prefix`, e.g. `"+1"`
/// for the North American Numbering Plan.
pub fn with_dial_prefix(prefix: &str) -> Vec<&'static Country> {
    COUNTRIES
        .iter()
        .filter(|c| !c.dial.is_empty() && c.dial.starts_with(prefix))
        .collect()
}

/// Converts a three-letter code to its two-letter code.
pub fn alpha3_to_alpha2(alpha3: &str) -> Option<&'static str> {
    by_alpha3(alpha3).map(|c| c.alpha2)
}

/// Converts a two-letter code to its three-letter code.
pub fn alpha2_to_alpha3(alpha2: &str) -> Option<&'static str> {
    by_alpha2(alpha2).map(|c| c.alpha3)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_by_alpha2() {
        for pair in COUNTRIES.windows(2) {
            assert!(pair[0].alpha2 < pair[1].alpha2, "{} before {}", pair[0].alpha2, pair[1].alpha2);
        }
    }

    #[test]
    fn alpha2_lookups() {
        assert_eq!(by_alpha2("CH").map(|c| c.name), Some("Switzerland"));
        assert_eq!(by_alpha2("ZW").map(|c| c.numeric), Some(716));
        assert_eq!(by_alpha2("XX"), None);
    }

    #[test]
    fn numeric_and_name_lookups() {
        assert_eq!(by_numeric(276).map(|c| c.alpha2), Some("DE"));
        assert_eq!(by_name("japan").map(|c| c.alpha3), Some("JPN"));
    }

    #[test]
    fn currency_and_dial() {
        assert_eq!(currency("AQ"), None);
        assert_eq!(currency("CH"), Some("CHF"));
        assert_eq!(dial_code("US"), Some("+1"));
        assert!(with_dial_prefix("+1").len() > 20);
        assert!(using_currency("EUR").iter().any(|c| c.alpha2 == "FR"));
    }
}
